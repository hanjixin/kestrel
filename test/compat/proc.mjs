import { spawn, exec, execSync, execFileSync, spawnSync, execFile } from "node:child_process";
import { promisify } from "node:util";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
const out = [];
out.push(execSync("echo hello && echo err 1>&2", { stdio: ["pipe", "pipe", "pipe"] }).toString().trim());
out.push(execFileSync("printf", ["%s-%s", "a", "b"], { encoding: "utf8" }));
const r = spawnSync("sh", ["-c", "cat; exit 3"], { input: "piped-in" });
out.push(r.status + ":" + r.stdout.toString());
try { execSync("exit 7", { stdio: "pipe" }); } catch (e) { out.push("status=" + e.status); }
const { stdout } = await promisify(exec)("echo via-exec");
out.push(stdout.trim());
const ef = await promisify(execFile)("uname", ["-s"]);
out.push(ef.stdout.trim());
const child = spawn("cat", []);
let data = "";
child.stdout.on("data", (c) => (data += c));
child.stdin.write("line1\n"); child.stdin.end("line2\n");
const code = await new Promise((res) => child.on("close", res));
out.push(code + ":" + JSON.stringify(data));
const bad = spawn("definitely-not-a-binary-xyz");
const err = await new Promise((res) => bad.on("error", res));
out.push(err.code);
// fd API
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "kfd-"));
const f = path.join(tmp, "a.bin");
const fd = fs.openSync(f, "w+");
fs.writeSync(fd, "hello world");
fs.writeSync(fd, Buffer.from("!!"), 0, 2, 5);
const buf = Buffer.alloc(5);
out.push(fs.readSync(fd, buf, 0, 5, 0) + ":" + buf.toString() + ":" + fs.fstatSync(fd).size);
fs.ftruncateSync(fd, 4); fs.closeSync(fd);
out.push(fs.readFileSync(f, "utf8"));
const fh = await fs.promises.open(f, "r");
const { bytesRead, buffer } = await fh.read(Buffer.alloc(10), 0, 10, 0);
out.push(bytesRead + ":" + buffer.subarray(0, bytesRead).toString()); await fh.close();
fs.rmSync(tmp, { recursive: true });
console.log(out.join("\n"));
