import assert from 'node:assert/strict';
import vm from 'node:vm';
assert.equal(vm.runInNewContext('this[0]', {0:42}),42);
const context = vm.createContext({});
Object.defineProperty(context,'hidden',{value:42,enumerable:false,configurable:true});
Object.defineProperty(context,'globalThis',{value:context,enumerable:false,configurable:true});
Object.defineProperty(context,'API',{value:class API {},enumerable:false,configurable:true});
context[Symbol.for('vm-token')] = 7;
assert.equal(vm.runInContext('this[Symbol.for("vm-token")]',context),7);
assert.equal(vm.runInContext('hidden',context),42);
assert.equal(vm.runInContext('Object.prototype.propertyIsEnumerable.call(this, "hidden")',context),false);
let setterCalls = 0;
Object.defineProperty(context, 'hiddenSetter', {set() {setterCalls++;}, enumerable:false, configurable:true});
vm.runInContext('1 + 1', context);
assert.equal(setterCalls, 0);
assert.equal(vm.runInContext('globalThis.hidden',context),42);
assert.equal(vm.runInContext('new API() instanceof API',context),true);
vm.runInContext('globalThis.Error = Error',context);
assert.equal(typeof context.Error,'function');
vm.runInContext('globalThis.Error.prepareStackTrace = () => "formatted"',context);
assert.equal(typeof context.Error.prepareStackTrace,'function');
assert.equal(Object.keys(context).includes('hidden'),false);
console.log('vm non-enumerable globals ok');
