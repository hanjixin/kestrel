import assert, { equal, deepEqual } from 'node:assert/strict';
import bare from 'assert/strict';
import promises, { pipeline, finished } from 'node:stream/promises';
import barePromises from 'stream/promises';
import { Readable, Writable } from 'node:stream';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
assert.equal(assert, bare);
assert.equal(assert, require('node:assert/strict'));
assert.equal(promises, barePromises);
assert.equal(promises, require('node:stream/promises'));
assert.throws(() => equal(1, '1'));
assert.throws(() => deepEqual({ a: 1 }, { a: '1' }));
let result = '';
const sink = new Writable({ write(chunk, enc, cb) { result += chunk; cb(); } });
await pipeline(Readable.from(['a', 'b']), sink);
await finished(sink);
assert.equal(result, 'ab');
console.log('builtin subpaths ok');
